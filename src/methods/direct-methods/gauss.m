
function T = gauss(T)
    % Метод Гаусса, специализированный под трёхдиагональную матрицу
    % системы для внутренних узлов (диагонали 1, -2, 1).
    % Полная матрица не хранится: нули вне трёх диагоналей при исключении
    % не меняются, а внедиагональные элементы равны 1, поэтому хранятся
    % только главная диагональ d и правая часть b. Ведущий элемент
    % не выбирается: матрица с диагональным преобладанием, |d(i)| >= 1.
    % По сути это совпадает с прогонкой (thomas.m) при a = c = 1.
    nx = length(T);
    n = nx - 2;

    TL = T(1);
    TR = T(end);

    % Главная диагональ и правая часть
    d = -2 * ones(n, 1);
    b = zeros(n, 1);

    % Учет граничных условий
    b(1) = -TL;
    b(end) = -TR;

    % Прямой ход метода Гаусса
    for i = 2:n
        m = 1 / d(i-1);
        d(i) = d(i) - m;
        b(i) = b(i) - m * b(i-1);
    end

    % Обратная подстановка
    TInner = zeros(n, 1);
    TInner(n) = b(n) / d(n);

    for i = n-1:-1:1
        TInner(i) = (b(i) - TInner(i+1)) / d(i);
    end

    T(2:end-1) = TInner.';
end

