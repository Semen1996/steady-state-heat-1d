
function T = thomas(T)
    nx = length(T);
    n = nx - 2;

    % Граничные температуры
    TL = T(1);
    TR = T(end);

    % Коэффициенты трехдиагональной системы
    a = ones(n, 1);       % Нижняя диагональ
    b = -2 * ones(n, 1);  % Главная диагональ
    c = ones(n, 1);       % Верхняя диагональ
    d = zeros(n, 1);      % Правая часть

    % Учет граничных условий
    a(1) = 0;
    c(end) = 0;
    d(1) = -TL;
    d(end) = -TR;

    % Прямой ход прогонки
    for i = 2:n
        m = a(i) / b(i-1);
        b(i) = b(i) - m * c(i-1);
        d(i) = d(i) - m * d(i-1);
    end

    % Обратный ход прогонки
    Tint = zeros(n, 1);
    Tint(n) = d(n) / b(n);

    for i = n-1:-1:1
        Tint(i) = (d(i) - c(i) * Tint(i+1)) / b(i);
    end

    % Записываем температуры внутренних узлов
    T(2:end-1) = Tint.';
end

